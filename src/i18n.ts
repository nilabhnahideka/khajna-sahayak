export const strings: Record<Lang, Record<Key, string>> = { as, en };

const AS_DIGITS = '০১২৩৪৫৬৭৮৯';
/** Render numbers with Assamese digits in Assamese mode. */
export function num(n: number | string, lang: Lang): string {
  const s = typeof n === 'number' ? n.toLocaleString('en-IN') : n;
  return lang === 'as' ? s.replace(/[0-9]/g, (d) => AS_DIGITS[+d]) : s;
}

export function translator(lang: Lang) {
  return (key: string) => (strings[lang] as Record<string, string>)[key] ?? key;
}
